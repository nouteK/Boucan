/**
 * Generates the derived contract artifacts from the single source of truth
 * (Zod schemas in shared/src/contracts + the real engine):
 *
 *   shared/schemas/*.json   JSON Schema of every entity and message
 *   shared/fixtures/*.json  representative states captured from real matches
 *   shared/fixtures/index.ts typed access to the fixtures
 *
 *   npm run contract:generate          (re)write the files
 *   npm run contract:check             fail if they are out of date (CI)
 */
import './deterministic';
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { z } from 'zod';
import * as contract from '@boucan/shared';
import { CLIENT_MESSAGES, makeError, PROTOCOL_VERSION, type ServerMessage } from '@boucan/shared';
import { DEFAULT_GAME_CONFIG } from '../src/config/game-config';
import { Harness, type TestClient } from '../test/harness';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../../shared');
const check = process.argv.includes('--check');
const outputs = new Map<string, string>();

function emit(relative: string, data: unknown): void {
  outputs.set(relative, typeof data === 'string' ? data : `${JSON.stringify(data, null, 2)}\n`);
}

// ─── JSON Schemas ─────────────────────────────────────────────────────────────

const GENERATED_NOTE = 'GENERATED by `npm run contract:generate` from shared/src/contracts — do not edit.';

function schema(name: string, zod: z.ZodType, io: 'input' | 'output'): void {
  const json = z.toJSONSchema(zod, { unrepresentable: 'any', io }) as Record<string, unknown>;
  emit(`schemas/${name}.schema.json`, { ...json, title: name, $comment: GENERATED_NOTE });
}

