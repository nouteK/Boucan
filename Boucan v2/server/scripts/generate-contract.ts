// ─── Write or check ───────────────────────────────────────────────────────────

const stale: string[] = [];
for (const [relative, content] of outputs) {
  const path = join(root, relative);
  let current: string | null = null;
  try {
    current = readFileSync(path, 'utf8');
  } catch {
    current = null;
  }
  if (current === content) continue;
  stale.push(relative);
  if (!check) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
  }
}
// Remove generated files that no longer exist in the contract.
for (const dir of ['schemas/model', 'schemas/messages', 'schemas/messages/client']) {
  let files: string[] = [];
  try {
    files = readdirSync(join(root, dir)).filter((f) => f.endsWith('.json'));
  } catch {
    continue;
  }
  for (const f of files) {
    const rel = `${dir}/${f}`;
    if (!outputs.has(rel)) {
      stale.push(`${rel} (obsolete)`);
      if (!check) rmSync(join(root, rel));
    }
  }
}

if (check) {
  if (stale.length > 0) {
    console.error(`Contract artifacts are out of date (${stale.length}):\n  ${stale.join('\n  ')}\nRun: npm run contract:generate`);
    process.exit(1);
  }
  console.log(`Contract artifacts up to date (${outputs.size} files).`);
} else {
  console.log(`Generated ${outputs.size} files (${stale.length} changed) in shared/.`);
}
